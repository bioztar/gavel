/**
 * The chair's eval set: ten frozen meetings, each one line, five scores.
 *
 *   pnpm evals                     offline — templates speak, judged dimensions not run
 *   pnpm evals -- --model          the real Nebius composer writes the lines
 *   pnpm evals -- --model --judge  the full scored pass (needs NEBIUS_API_KEY)
 *   pnpm evals -- --out /tmp/x.md --config DIR --cases DIR
 *
 * `--model` and `--judge` need NEBIUS_API_KEY in the environment (or the repo-root .env);
 * without it this exits with `NEBIUS_API_KEY is not set` before any call is made. Offline
 * is the default so the table can be regenerated by anyone, with no key and no network.
 */
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { parseArgs } from "node:util";

process.env.GAVEL_MASTRA_STORAGE ??= "off";

const [
  { env },
  { loadConfig },
  { StubLlm },
  { MastraLlm },
  { setConfig },
  { log },
  { CASES_DIR, EVALS_DIR, loadCases },
  { generateLine },
  { NebiusJudge },
  { DIMENSIONS, scoreLine },
] = await Promise.all([
  import("../src/env"),
  import("../src/config"),
  import("../src/chair/llm"),
  import("../src/chair/mastraLlm"),
  import("../src/runtime"),
  import("../src/log"),
  import("./cases"),
  import("./harness"),
  import("./judge"),
  import("./score"),
]).catch((error) => {
  throw new Error("could not load evaluation dependencies", { cause: error });
});
type Judge = import("./judge").Judge;
type Scores = import("./score").Scores;

const { values } = parseArgs({
  options: {
    model: { type: "boolean", default: false },
    judge: { type: "boolean", default: false },
    config: { type: "string" },
    cases: { type: "string" },
    out: { type: "string" },
  },
});

if ((values.model || values.judge) && !env.nebiusApiKey) {
  console.error("NEBIUS_API_KEY is not set");
  process.exit(1);
}

log.setQuiet(true);
const config = loadConfig(values.config);
setConfig(config);

const cases = loadCases(values.cases ? resolve(values.cases) : CASES_DIR);
const out = values.out ? resolve(values.out) : resolve(EVALS_DIR, "results.md");
const judge: Judge | undefined = values.judge ? new NebiusJudge(config) : undefined;

interface Row {
  id: string;
  title: string;
  trigger: string;
  kind: string;
  line: string;
  source: string;
  scores: Scores;
  notes: string;
}

const rows: Row[] = [];
for (const c of cases) {
  // Each case gets its own engine: no line cache, no template rotation carried across cases.
  const llm = values.model
    ? new MastraLlm(() => config.models, () => {})
    : new StubLlm();
  const { intervention, composed } = await generateLine(c, config, llm);
  const scores = await scoreLine(c, intervention, composed.line, judge);
  const failures = DIMENSIONS.filter((d) => scores[d.key].pass === false).map((d) => scores[d.key].detail);
  if (intervention.kind !== c.expect.kind) failures.unshift(`fired \`${intervention.kind}\`, the case expects \`${c.expect.kind}\``);
  rows.push({
    id: c.id,
    title: c.title,
    trigger: intervention.trigger,
    kind: intervention.kind,
    line: composed.line,
    source: composed.source,
    scores,
    notes: failures.length ? failures.join("; ") : "—",
  });
  console.log(`${c.id.padEnd(28)} ${intervention.kind.padEnd(15)} [${composed.source}] ${composed.line}`);
}

writeFileSync(out, table(rows));
console.log(`\n${out}`);
process.exit(0);

function cell(s: string): string {
  return s.replace(/\|/g, "\\|").replace(/\n/g, " ").trim() || "—";
}

function mark(pass: boolean | null): string {
  return pass === null ? "—" : pass ? "pass" : "**fail**";
}

function table(rows: Row[]): string {
  const mode = `${values.model ? `nebius \`${config.models.profiles.normal.model}\`` : "offline, YAML templates"} · judged dimensions ${values.judge ? "scored by nebius" : "**not run**"}`;
  const head = ["Case", "Trigger", "Generated line", ...DIMENSIONS.map((d) => d.label), "Notes"];
  const lines = [
    "# Chair eval results",
    "",
    `Ten frozen chair states (\`evals/cases/\`) through the chair's own trigger and prompt path, scored against the rubric in [QUALITY.md](../../../docs/QUALITY.md). Regenerate with \`pnpm evals\`.`,
    "",
    `Generated: ${new Date().toISOString().slice(0, 10)} · lines: ${mode}`,
    "",
    `| ${head.join(" | ")} |`,
    `| ${head.map(() => "---").join(" | ")} |`,
  ];
  for (const r of rows) {
    lines.push(
      `| ${cell(r.title)}<br><sub>\`${r.id}\`</sub> | \`${r.kind}\`<br><sub>${r.trigger}</sub> | ${cell(r.line)}<br><sub>[${r.source}]</sub> | ${DIMENSIONS.map((d) => mark(r.scores[d.key].pass)).join(" | ")} | ${cell(r.notes)} |`,
    );
  }
  lines.push("", "## What each case is for", "");
  for (const c of cases) lines.push(`- **${c.title}** (\`${c.id}\`) — ${c.notes}`);
  lines.push(
    "",
    "## Reading the scores",
    "",
    "- *names the right person*, *under 20 words* and *hands the floor somewhere specific* are counted in code (`evals/score.ts`) against each case's expectations — never asked of a model.",
    "- *polite enough for a real meeting* and *invents nothing* are judged by the model and read `—` until someone runs `pnpm evals -- --model --judge` with a key.",
    "",
  );
  return lines.join("\n");
}
